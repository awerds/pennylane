import { useEffect, useMemo, useState } from 'react';
import { Masthead } from './components/Masthead';
import { SyncTicker } from './components/SyncTicker';
import { HeroSpotlight } from './components/HeroSpotlight';
import { FilterBar } from './components/FilterBar';
import { PropertyCard } from './components/PropertyCard';
import { PropertyDossierModal } from './components/PropertyDossierModal';
import { SyncLedgerModal } from './components/SyncLedgerModal';
import type { ChangelogFeed, FilterState, ListingsFeed, PropertyListing } from './types';
import { simulateNextDayClient } from './utils/format';

const SAVED_STORAGE_KEY = 'pennylane:saved-listings:v1';

const DEFAULT_FILTERS: FilterState = {
  lens: 'all',
  region: 'All',
  maxPrice: 0,
  sort: 'score',
  query: '',
};

function loadSavedIds(): string[] {
  try {
    const raw = localStorage.getItem(SAVED_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed.filter((x): x is string => typeof x === 'string') : [];
  } catch {
    return [];
  }
}

export function App() {
  const [liveFeed, setLiveFeed] = useState<ListingsFeed | null>(null);
  const [liveChangelog, setLiveChangelog] = useState<ChangelogFeed | null>(null);
  const [liveReserve, setLiveReserve] = useState<PropertyListing[]>([]);

  const [feed, setFeed] = useState<ListingsFeed | null>(null);
  const [changelog, setChangelog] = useState<ChangelogFeed | null>(null);
  const [reservePool, setReservePool] = useState<PropertyListing[]>([]);

  const [isSimulated, setIsSimulated] = useState(false);
  const [simulationNotice, setSimulationNotice] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const [filters, setFilters] = useState<FilterState>(DEFAULT_FILTERS);
  const [savedIds, setSavedIds] = useState<string[]>(() => loadSavedIds());
  const [selectedListing, setSelectedListing] = useState<PropertyListing | null>(null);
  const [ledgerOpen, setLedgerOpen] = useState(false);

  // Load static daily JSON editions generated by scripts/sync-listings.mjs
  useEffect(() => {
    let active = true;
    async function loadEdition() {
      try {
        const [listingsRes, changelogRes, reserveRes] = await Promise.all([
          fetch('./data/listings.json'),
          fetch('./data/changelog.json'),
          fetch('./data/reserve.json').catch(() => null),
        ]);
        if (!listingsRes.ok) throw new Error('Unable to load daily property index.');
        const listingsData: ListingsFeed = await listingsRes.json();
        const changelogData: ChangelogFeed = changelogRes.ok
          ? await changelogRes.json()
          : { lastSyncedAt: listingsData.syncedAt, totalRemovedUnderContract: 0, runs: [], removedArchive: [] };
        const reserveData: PropertyListing[] =
          reserveRes && reserveRes.ok ? await reserveRes.json() : [];

        if (!active) return;
        setLiveFeed(listingsData);
        setLiveChangelog(changelogData);
        setLiveReserve(reserveData);
        setFeed(listingsData);
        setChangelog(changelogData);
        setReservePool(reserveData);

        // Deep-link support (?property=<id>)
        const propertyId = new URLSearchParams(window.location.search).get('property');
        if (propertyId) {
          const match = listingsData.listings.find((l) => l.id === propertyId);
          if (match) setSelectedListing(match);
        }
      } catch (err) {
        if (!active) return;
        setError(err instanceof Error ? err.message : 'Failed to load edition.');
      } finally {
        if (active) setLoading(false);
      }
    }
    void loadEdition();
    return () => {
      active = false;
    };
  }, []);

  // Persist saved watchlist
  useEffect(() => {
    try {
      localStorage.setItem(SAVED_STORAGE_KEY, JSON.stringify(savedIds));
    } catch {
      // Ignore storage quota / privacy mode errors
    }
  }, [savedIds]);

  const savedSet = useMemo(() => new Set(savedIds), [savedIds]);

  const toggleSave = (id: string) => {
    setSavedIds((prev) => (prev.includes(id) ? prev.filter((item) => item !== id) : [...prev, id]));
  };

  const handleInspect = (listing: PropertyListing) => {
    setSelectedListing(listing);
    const url = new URL(window.location.href);
    url.searchParams.set('property', listing.id);
    window.history.replaceState({}, '', url);
  };

  const handleCloseDossier = () => {
    setSelectedListing(null);
    const url = new URL(window.location.href);
    if (url.searchParams.has('property')) {
      url.searchParams.delete('property');
      window.history.replaceState({}, '', url);
    }
  };

  const handleSimulateNextDay = () => {
    if (!feed || !changelog) return;
    const { nextFeed, nextChangelog, nextReserve, summaryText } = simulateNextDayClient(
      feed,
      changelog,
      reservePool
    );
    setFeed(nextFeed);
    setChangelog(nextChangelog);
    setReservePool(nextReserve);
    setIsSimulated(true);
    setSimulationNotice(summaryText);
  };

  const handleResetSimulation = () => {
    if (!liveFeed || !liveChangelog) return;
    setFeed(liveFeed);
    setChangelog(liveChangelog);
    setReservePool(liveReserve);
    setIsSimulated(false);
    setSimulationNotice(null);
  };

  const allListings = feed?.listings ?? [];

  const regions = useMemo(() => {
    return Array.from(new Set(allListings.map((l) => l.region))).sort();
  }, [allListings]);

  const counts = useMemo(
    () => ({
      all: allListings.length,
      exceptional: allListings.filter((l) => l.categories.includes('exceptional')).length,
      deal: allListings.filter((l) => l.categories.includes('deal')).length,
      new: allListings.filter((l) => l.categories.includes('new')).length,
      saved: allListings.filter((l) => savedSet.has(l.id)).length,
    }),
    [allListings, savedSet]
  );

  const filteredListings = useMemo(() => {
    const q = filters.query.trim().toLowerCase();
    const list = allListings.filter((item) => {
      if (filters.lens === 'saved' && !savedSet.has(item.id)) return false;
      if (
        filters.lens !== 'all' &&
        filters.lens !== 'saved' &&
        !item.categories.includes(filters.lens)
      ) {
        return false;
      }
      if (filters.region !== 'All' && item.region !== filters.region) return false;
      if (filters.maxPrice > 0 && item.price > filters.maxPrice) return false;
      if (q) {
        const haystack = `${item.title} ${item.city} ${item.state} ${item.architecturalStyle} ${item.editorialNote} ${item.raritySignals.join(' ')}`.toLowerCase();
        if (!haystack.includes(q)) return false;
      }
      return true;
    });

    const sorted = [...list];
    if (filters.sort === 'newest') {
      sorted.sort((a, b) => a.daysOnMarket - b.daysOnMarket || b.scores.overall - a.scores.overall);
    } else if (filters.sort === 'discount') {
      sorted.sort((a, b) => a.medianDeltaPct - b.medianDeltaPct || b.priceCutPct - a.priceCutPct);
    } else if (filters.sort === 'price-asc') {
      sorted.sort((a, b) => a.price - b.price);
    } else if (filters.sort === 'price-desc') {
      sorted.sort((a, b) => b.price - a.price);
    } else {
      sorted.sort((a, b) => b.scores.overall - a.scores.overall || a.daysOnMarket - b.daysOnMarket);
    }
    return sorted;
  }, [allListings, filters, savedSet]);

  const showHero =
    filters.lens === 'all' &&
    filters.region === 'All' &&
    filters.maxPrice === 0 &&
    filters.query.trim() === '' &&
    filteredListings.length > 0;

  const heroListing = showHero ? filteredListings[0] : null;
  const gridListings = showHero ? filteredListings.slice(1) : filteredListings;

  if (loading) {
    return (
      <div className="flex min-h-dvh items-center justify-center bg-[var(--paper)] px-6">
        <div className="text-center">
          <div className="font-serif-editorial text-4xl text-[var(--ink)]">PennyLane</div>
          <p className="mt-2 font-mono-tech text-xs uppercase tracking-widest text-[var(--ink-soft)]">
            Loading today&apos;s edition...
          </p>
        </div>
      </div>
    );
  }

  if (error || !feed) {
    return (
      <div className="flex min-h-dvh items-center justify-center bg-[var(--paper)] px-6">
        <div className="max-w-md border border-[var(--rule)] bg-[var(--paper-raised)] p-8 text-center">
          <h1 className="font-serif-editorial text-3xl text-[var(--ink)]">Edition Unavailable</h1>
          <p className="mt-2 text-sm text-[var(--ink-soft)]">
            {error || 'Run `npm run sync` to generate today’s daily listing feed.'}
          </p>
        </div>
      </div>
    );
  }

  return (
    <div className="min-h-dvh bg-[var(--paper)] text-[var(--ink)]">
      <Masthead
        editionNumber={feed.editionNumber}
        syncedAt={feed.syncedAt}
        activeCount={feed.summary.activeCount}
        savedCount={counts.saved}
        removedTotal={changelog?.totalRemovedUnderContract ?? 0}
        isSimulated={isSimulated}
        onOpenLedger={() => setLedgerOpen(true)}
        onSelectSaved={() =>
          setFilters((prev) => ({ ...prev, lens: prev.lens === 'saved' ? 'all' : 'saved' }))
        }
      />

      <SyncTicker
        syncedAt={feed.syncedAt}
        provider={feed.provider}
        summary={feed.summary}
        isSimulated={isSimulated}
        simulationNotice={simulationNotice}
        onSimulateDay={handleSimulateNextDay}
        onResetSimulation={handleResetSimulation}
        onOpenLedger={() => setLedgerOpen(true)}
      />

      <main>
        {heroListing && (
          <HeroSpotlight
            listing={heroListing}
            isSaved={savedSet.has(heroListing.id)}
            onInspect={handleInspect}
            onToggleSave={toggleSave}
          />
        )}

        <FilterBar
          filters={filters}
          counts={counts}
          regions={regions}
          resultCount={filteredListings.length}
          onChange={(patch) => setFilters((prev) => ({ ...prev, ...patch }))}
          onReset={() => setFilters(DEFAULT_FILTERS)}
        />

        <section
          aria-label="Active property listings"
          className="mx-auto max-w-[1380px] px-5 py-8 sm:px-8 sm:py-10"
        >
          <div className="mb-6 flex items-baseline justify-between gap-4 border-b border-[var(--rule)] pb-3">
            <h2 className="font-serif-editorial text-2xl text-[var(--ink)] sm:text-3xl">
              {filters.lens === 'all'
                ? 'Active Market Dispatch'
                : filters.lens === 'exceptional'
                ? 'Architectural Outliers & Rare Finds'
                : filters.lens === 'deal'
                ? 'Below-Median Deals & Steep Price Cuts'
                : filters.lens === 'new'
                ? 'Fresh to Market (Last 72 Hours)'
                : 'Your Saved Watchlist'}
            </h2>
            <span className="font-mono-tech text-xs text-[var(--ink-soft)]">
              Showing {filteredListings.length} of {allListings.length}
            </span>
          </div>

          {gridListings.length === 0 && !heroListing ? (
            <div className="border border-[var(--rule)] bg-[var(--paper-raised)] px-6 py-16 text-center">
              <p className="font-serif-editorial text-2xl text-[var(--ink)]">
                No matching properties in today&apos;s edition.
              </p>
              <p className="mt-2 text-sm text-[var(--ink-soft)]">
                {filters.lens === 'saved'
                  ? 'Bookmark listings as you browse to track them here until they go under contract.'
                  : 'Try widening your price ceiling or clearing your search filters.'}
              </p>
              <button
                type="button"
                onClick={() => setFilters(DEFAULT_FILTERS)}
                className="mt-5 cursor-pointer border border-[var(--ink)] bg-[var(--ink)] px-4 py-2 text-xs font-medium text-[var(--paper)] hover:bg-[#2a2926]"
              >
                Reset All Filters
              </button>
            </div>
          ) : (
            <div className="grid grid-cols-1 gap-6 md:grid-cols-2 lg:grid-cols-3">
              {gridListings.map((listing) => (
                <PropertyCard
                  key={listing.id}
                  listing={listing}
                  isSaved={savedSet.has(listing.id)}
                  onInspect={handleInspect}
                  onToggleSave={toggleSave}
                />
              ))}
            </div>
          )}
        </section>
      </main>

      <footer className="mt-12 border-t border-[var(--rule)] bg-[var(--paper-raised)]">
        <div className="mx-auto flex max-w-[1380px] flex-col gap-4 px-5 py-8 text-xs text-[var(--ink-soft)] sm:flex-row sm:items-center sm:justify-between sm:px-8">
          <div>
            <span className="font-serif-editorial text-xl text-[var(--ink)]">PennyLane</span>
            <span className="mx-2 text-[var(--rule)]">·</span>
            <span>MIT Licensed Open-Source Real-Estate Index</span>
          </div>
          <div className="flex flex-wrap items-center gap-4 font-mono-tech text-[11px]">
            <span>Zero-Cost GitHub Pages + Actions</span>
            <span className="text-[var(--rule)]">/</span>
            <button
              type="button"
              onClick={() => setLedgerOpen(true)}
              className="cursor-pointer text-[var(--ink)] underline underline-offset-4 hover:text-[var(--vermilion)]"
            >
              View Removal Ledger &amp; Architecture
            </button>
          </div>
        </div>
      </footer>

      <PropertyDossierModal
        listing={selectedListing}
        isSaved={selectedListing ? savedSet.has(selectedListing.id) : false}
        onClose={handleCloseDossier}
        onToggleSave={toggleSave}
      />

      <SyncLedgerModal
        open={ledgerOpen}
        changelog={changelog}
        provider={feed.provider}
        onClose={() => setLedgerOpen(false)}
      />
    </div>
  );
}

export default App;

